// Helper to get drives with company info
export function getDriveById(id: string): Drive | undefined {
  return drives.find((d) => d.id === id);
}

export function getDrivesByCompany(companyId: string): Drive[] {
  return drives.filter((d) => d.companyId === companyId);
}

export function getOpenDrives(): Drive[] {
  return drives.filter((d) => d.status === "Open" || d.status === "Closing Soon");
}
